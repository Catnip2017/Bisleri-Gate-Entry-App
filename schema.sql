    document_no         VARCHAR(255)  PRIMARY KEY,
    document_type       VARCHAR(255),
    sub_document_type   VARCHAR(255),
    document_date       TIMESTAMPTZ,
    e_way_bill_no       VARCHAR(255),
    transporter_name    VARCHAR(255),
    vehicle_no          VARCHAR(255),
    irn_no              VARCHAR(255),
    from_warehouse_code VARCHAR(255),
    to_warehouse_code   VARCHAR(255),
    route_code          VARCHAR(255),
    total_quantity      INTEGER,
    site                VARCHAR(255),
    direct_dispatch     VARCHAR(255),
    salesman            VARCHAR(255),
    itemid              VARCHAR(255),
    linenum             NUMERIC
);

CREATE INDEX IF NOT EXISTS idx_mfabric_to_vehicle_no
    ON mfabric_transferorder_rgp_data (vehicle_no);
CREATE INDEX IF NOT EXISTS idx_mfabric_to_document_date
    ON mfabric_transferorder_rgp_data (document_date);
