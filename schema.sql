    ON mfabric_transferorder_rgp_data (from_warehouse_code, to_warehouse_code);

COMMENT ON TABLE  mfabric_transferorder_rgp_data             IS 'Staging — Mfabric Transfer Order / RGP raw sync';
COMMENT ON COLUMN mfabric_transferorder_rgp_data.document_no IS 'PK for SQLAlchemy only; ERP may have multi-line rows';


-- ----------------------------------------------------------------
-- 8. RAW MATERIALS DATA
--    Gate entry log for Raw Material vehicles.
--    Separate from insights_data (which covers FG movements).
-- ----------------------------------------------------------------
CREATE TABLE IF NOT EXISTS raw_materials_data (
    id                       SERIAL        PRIMARY KEY,

    -- Core entry fields
    gate_entry_no            VARCHAR(50)   NOT NULL,
    gate_type                VARCHAR(20)   NOT NULL,     -- 'Gate-In' or 'Gate-Out'
    vehicle_no               VARCHAR(50)   NOT NULL,
    document_no              VARCHAR(50)   NOT NULL,
    name_of_party            VARCHAR(255)  NOT NULL,
    description_of_material  VARCHAR(255)  NOT NULL,
    quantity                 VARCHAR(255)  NOT NULL,
    date_time                TIMESTAMP     NOT NULL,
    security_name            VARCHAR(100)  NOT NULL,
    security_username        VARCHAR(50)   NOT NULL,
    warehouse_code           VARCHAR(50)   NOT NULL,
    site_code                VARCHAR(50)   NOT NULL,

    -- Edit tracking (48-hour window, same logic as insights_data)
    last_edited_at           TIMESTAMP,
    edit_count               INTEGER       DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_raw_materials_gate_entry_no
    ON raw_materials_data (gate_entry_no);
CREATE INDEX IF NOT EXISTS idx_raw_materials_date_time
    ON raw_materials_data (date_time);
CREATE INDEX IF NOT EXISTS idx_raw_materials_warehouse_code
    ON raw_materials_data (warehouse_code);
CREATE INDEX IF NOT EXISTS idx_raw_materials_vehicle_no
    ON raw_materials_data (vehicle_no);
CREATE INDEX IF NOT EXISTS idx_raw_materials_security_username
    ON raw_materials_data (security_username);

COMMENT ON TABLE  raw_materials_data               IS 'Gate entry log — Raw Material vehicle movements (in/out)';
COMMENT ON COLUMN raw_materials_data.gate_type     IS '''Gate-In'' or ''Gate-Out''';
COMMENT ON COLUMN raw_materials_data.quantity      IS 'Stored as text to support units (e.g. "500 KG", "20 MT")';


