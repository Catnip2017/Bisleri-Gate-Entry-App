    document_no       VARCHAR(255)  PRIMARY KEY,
    document_type     VARCHAR(255),
    document_date     TIMESTAMPTZ,
    e_way_bill_no     VARCHAR(255),
    transporter_name  VARCHAR(255),
    vehicle_no        VARCHAR(255),
    irn_no            VARCHAR(255),
    customer_code     VARCHAR(255),
    customer_name     VARCHAR(255),
    total_quantity    INTEGER,
    site              VARCHAR(255),
    itemid            VARCHAR(255),
    linenum           NUMERIC
);

CREATE INDEX IF NOT EXISTS idx_mfabric_inv_vehicle_no
    ON mfabric_invoice_data (vehicle_no);
CREATE INDEX IF NOT EXISTS idx_mfabric_inv_document_date
    ON mfabric_invoice_data (document_date);

COMMENT ON TABLE  mfabric_invoice_data             IS 'Staging — Mfabric Invoice raw sync';
COMMENT ON COLUMN mfabric_invoice_data.document_no IS 'PK for SQLAlchemy only; ERP may have multi-line rows';


-- ----------------------------------------------------------------
-- 7. MFABRIC TRANSFER ORDER / RGP DATA  (staging)
--    Raw records for inter-warehouse Transfer Orders and RGP docs.
-- ----------------------------------------------------------------
