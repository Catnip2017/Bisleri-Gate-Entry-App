-- ================================================================
-- TABLES
-- ================================================================

-- ----------------------------------------------------------------
-- 1. LOCATION MASTER
--    Master list of warehouses / sites.
--    Synced from Mfabric — do not manually edit rows.
-- ----------------------------------------------------------------
CREATE TABLE IF NOT EXISTS location_master (
    warehouse_code  VARCHAR(50)  PRIMARY KEY,
    warehouse_name  VARCHAR(255),
    site_code       VARCHAR(50),
    warehouse_id    VARCHAR(50)
);

CREATE INDEX IF NOT EXISTS idx_location_master_site_code
    ON location_master (site_code);

COMMENT ON TABLE  location_master                IS 'Warehouse / site master — synced from Mfabric ERP';
COMMENT ON COLUMN location_master.warehouse_code IS 'Unique warehouse identifier (PK)';
COMMENT ON COLUMN location_master.site_code      IS 'Parent site grouping multiple warehouses';


-- ----------------------------------------------------------------
-- 2. USERS MASTER
--    Application users: security guards, security admins, IT admin.
--    Roles: securityguard | securityadmin | itadmin
-- ----------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users_master (
    username        VARCHAR(50)  PRIMARY KEY,
    first_name      VARCHAR(255),
    last_name       VARCHAR(255),
    role            VARCHAR(50),
    warehouse_code  VARCHAR(50)  REFERENCES location_master (warehouse_code),
    warehouse_name  VARCHAR(255),
    site_code       VARCHAR(50),
    password        VARCHAR(255),
    email           VARCHAR(255),
    phone_number    VARCHAR(20),
    last_login      TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_users_master_role
    ON users_master (role);
CREATE INDEX IF NOT EXISTS idx_users_master_warehouse_code
    ON users_master (warehouse_code);
CREATE INDEX IF NOT EXISTS idx_users_master_site_code
    ON users_master (site_code);

COMMENT ON TABLE  users_master              IS 'Application users — managed via Admin → Register Users';
COMMENT ON COLUMN users_master.username     IS 'Login username (PK)';
COMMENT ON COLUMN users_master.role         IS 'Comma-separated roles: securityguard, securityadmin, itadmin';
COMMENT ON COLUMN users_master.password     IS 'bcrypt hash — generated by passlib CryptContext';


-- ----------------------------------------------------------------
-- 3. INSIGHTS DATA
--    Central gate-entry log. Every vehicle movement (Gate-In /
--    Gate-Out) creates one row. Includes the 3-colour edit system
--    (YELLOW = needs completion, GREEN = complete, BLACK = expired).
-- ----------------------------------------------------------------
CREATE TABLE IF NOT EXISTS insights_data (
    id                  SERIAL       PRIMARY KEY,

    -- Core movement fields
    gate_entry_no       VARCHAR(50),
    document_type       VARCHAR(50),
    sub_document_type   VARCHAR(50),
    document_no         VARCHAR(100),
    vehicle_no          VARCHAR(50),
    warehouse_name      VARCHAR(100),
    date                TIMESTAMP,                   -- date portion of gate entry
    time                TIME,                        -- time portion of gate entry
    movement_type       VARCHAR(20),                 -- 'Gate-In' or 'Gate-Out'
    remarks             TEXT,
    warehouse_code      VARCHAR(50),
    site_code           VARCHAR(50),
    security_name       VARCHAR(255),
    security_username   VARCHAR(255),
    document_date       TIMESTAMP,                   -- ERP document creation datetime

    -- Operational fields (3-colour edit system — 48-hour window)
    driver_name         VARCHAR(100),                -- required for GREEN status
    km_reading          VARCHAR(10),                 -- KM-In or KM-Out reading
    loader_count        INTEGER,                     -- number of loaders
    loader_names        VARCHAR(200),                -- comma-separated loader names
    interlayer_sheet_count INTEGER   NOT NULL DEFAULT 0,  -- compulsory, defaults to 0
    last_edited_at      TIMESTAMP,                   -- last operational edit timestamp
    edit_count          INTEGER      DEFAULT 0       -- total number of edits made
);

CREATE INDEX IF NOT EXISTS idx_insights_data_gate_entry_no
    ON insights_data (gate_entry_no);
CREATE INDEX IF NOT EXISTS idx_insights_data_date
    ON insights_data (date);
CREATE INDEX IF NOT EXISTS idx_insights_data_warehouse_code
    ON insights_data (warehouse_code);
CREATE INDEX IF NOT EXISTS idx_insights_data_vehicle_no
    ON insights_data (vehicle_no);
CREATE INDEX IF NOT EXISTS idx_insights_data_security_username
    ON insights_data (security_username);
CREATE INDEX IF NOT EXISTS idx_insights_data_movement_type
    ON insights_data (movement_type);

COMMENT ON TABLE  insights_data                   IS 'Gate entry log — FG vehicle movements (in/out)';
COMMENT ON COLUMN insights_data.gate_entry_no     IS 'Format: GATE-YYYYMMDD-NNNN (generated by frontend)';
COMMENT ON COLUMN insights_data.movement_type     IS '''Gate-In'' or ''Gate-Out''';
COMMENT ON COLUMN insights_data.edit_count        IS 'Incremented on each operational edit; max edits within 48 hrs';
COMMENT ON COLUMN insights_data.driver_name       IS 'Required to move from YELLOW to GREEN edit status';
COMMENT ON COLUMN insights_data.km_reading        IS 'Required to move from YELLOW to GREEN edit status';
COMMENT ON COLUMN insights_data.loader_names      IS 'Required to move from YELLOW to GREEN edit status';
COMMENT ON COLUMN insights_data.interlayer_sheet_count IS 'Compulsory field, defaults to 0; required to move from YELLOW to GREEN edit status';


-- ----------------------------------------------------------------
-- 4. DOCUMENT DATA
--    Consolidated / enriched ERP document index. Built by the
--    data-sync service from the three Mfabric staging tables.
-- ----------------------------------------------------------------
CREATE TABLE IF NOT EXISTS document_data (
    document_no           VARCHAR(100)  PRIMARY KEY,
    site                  VARCHAR(100),
    document_type         VARCHAR(100),
    document_date         TIMESTAMP,
    e_way_bill_no         VARCHAR(100),
    transporter_name      VARCHAR(100),
    vehicle_no            VARCHAR(100),
    irn_no                VARCHAR(100),
    warehouse_code        VARCHAR(100),
    warehouse_name        VARCHAR(100),
    route_code            VARCHAR(100),
    route_no              VARCHAR(100),
    customer_code         VARCHAR(100),
    customer_name         VARCHAR(100),
    direct_dispatch       VARCHAR(100),
    total_quantity        VARCHAR(100),
    gate_entry_no         VARCHAR(20),
    from_warehouse_code   VARCHAR(100),
    to_warehouse_code     VARCHAR(100),
    sub_document_type     VARCHAR(100),
    salesman              VARCHAR(100)
);

CREATE INDEX IF NOT EXISTS idx_document_data_vehicle_no
    ON document_data (vehicle_no);
CREATE INDEX IF NOT EXISTS idx_document_data_document_date
    ON document_data (document_date);
CREATE INDEX IF NOT EXISTS idx_document_data_warehouse_code
    ON document_data (warehouse_code);
CREATE INDEX IF NOT EXISTS idx_document_data_gate_entry_no
    ON document_data (gate_entry_no);
CREATE INDEX IF NOT EXISTS idx_document_data_document_type
    ON document_data (document_type);

COMMENT ON TABLE  document_data              IS 'Consolidated ERP document index — built by data-sync service';
COMMENT ON COLUMN document_data.document_no  IS 'ERP document number (PK)';


-- ----------------------------------------------------------------
-- 5. MFABRIC DELIVERY CHALLAN DATA  (staging)
--    Raw records pulled from Mfabric for Delivery Challans.
--    document_no is used as PK only for SQLAlchemy compatibility —
--    duplicates may exist in the source ERP.
-- ----------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mfabric_deliverychallan_data (
    document_no       VARCHAR(255)  PRIMARY KEY,
    document_type     VARCHAR(255),
    document_date     TIMESTAMPTZ,
    e_way_bill_no     VARCHAR(255),
    transporter_name  VARCHAR(255),
    vehicle_no        VARCHAR(255),
    irn_no            VARCHAR(255),
    route_no          VARCHAR(255),
    total_quantity    INTEGER,
    site              VARCHAR(255),
    customer_code     VARCHAR(255),
    customer_name     VARCHAR(255),
    itemid            VARCHAR(255),
    linenum           NUMERIC
);

CREATE INDEX IF NOT EXISTS idx_mfabric_dc_vehicle_no
    ON mfabric_deliverychallan_data (vehicle_no);
CREATE INDEX IF NOT EXISTS idx_mfabric_dc_document_date
    ON mfabric_deliverychallan_data (document_date);

COMMENT ON TABLE  mfabric_deliverychallan_data             IS 'Staging — Mfabric Delivery Challan raw sync';
COMMENT ON COLUMN mfabric_deliverychallan_data.document_no IS 'PK for SQLAlchemy only; ERP may have multi-line rows';


-- ----------------------------------------------------------------
-- 6. MFABRIC INVOICE DATA  (staging)
--    Raw records pulled from Mfabric for Invoices.
-- ----------------------------------------------------------------
